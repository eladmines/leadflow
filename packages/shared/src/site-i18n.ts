const TEXT: Record<SiteLanguage, SiteText> = { he, en };

/** The fixed texts for a site in this language (Hebrew when unset: sites made before D-142). */
export const siteText = (lang: SiteLanguage | undefined): SiteText => TEXT[lang ?? 'he'];

/** Fills `{0}` in a site text. */
export const fill = (text: string, value: string | number) => text.replace('{0}', String(value));

/** A form error in the site's language (shared schemas write them in Hebrew). */
export const siteError = (lang: SiteLanguage | undefined, message: string) =>
  siteText(lang).errors[message] ?? message;
