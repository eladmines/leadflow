# -- validation ----------------------------------------------------------------------------------------


def _bot_text(v: Any) -> str | None:
    """A custom message; empty means "use the default"."""
    if v is None:
        return None
    if not isinstance(v, str):
        raise ValueError("Expected string")
    s = v.strip()
    if len(s) > BOT_TEXT_MAX:
        raise ValueError(M["tooLong"])
    if any(p not in BOT_PLACEHOLDERS for p in re.findall(r"\{[^}]*\}", s)):
        raise ValueError(M["unknownPlaceholder"])
    return s or None


def _link(v: Any) -> str | None:
    if v is None or (isinstance(v, str) and v.strip() == ""):
        return None
    if not isinstance(v, str):
        raise ValueError(M["linkInvalid"])
    s = v.strip()
    if len(s) > 500 or not re.fullmatch(r"https://[^\s]+\.[^\s]+", s):
        raise ValueError(M["linkInvalid"])
    return s


def _asset_ids(v: Any) -> list[str]:
    if v is None:
        return []
    if not isinstance(v, list):
        raise ValueError("Expected array")
    if len(v) > SHOWCASE_MAX_IMAGES:
        raise ValueError(M["tooManyImages"])
    for x in v:
        uuid.UUID(str(x))
    return [str(x) for x in v]


_ID = r"[a-z0-9-]{1,40}"


def _status_id(v: Any) -> str:
    if not isinstance(v, str) or not re.fullmatch(_ID, v):
        raise ValueError("Invalid")
    return v


def _label(v: Any) -> str:
    s = v.strip() if isinstance(v, str) else ""
    if not s:
        raise ValueError(M["statusLabelRequired"])
    if len(s) > 40:
        raise ValueError(M["statusLabelTooLong"])
    return s


def _status_text(v: Any) -> str:
    s = v.strip() if isinstance(v, str) else ""
    if not s:
        raise ValueError(M["statusTextRequired"])
    if len(s) > 1000:
        raise ValueError(M["statusTextTooLong"])
    return s


def _question_text(v: Any) -> str:
    s = v.strip() if isinstance(v, str) else ""
    if not s:
        raise ValueError(M["questionRequired"])
    if len(s) > 300:
        raise ValueError(M["questionTooLong"])
    return s


def _auto_reply_text(v: Any) -> str | None:
    if v is None:
        return None
    if not isinstance(v, str):
        raise ValueError("Expected string")
    s = v.strip()
    if len(s) > 1000:
        raise ValueError(M["statusTextTooLong"])
    return s


