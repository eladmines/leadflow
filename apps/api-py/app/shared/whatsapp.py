# -- stored values (lenient: invalid stored JSON reads as "unset") --------------------------------------


def parse_bot_texts(raw: Any) -> dict[str, str]:
    """The business's own wording as stored; anything that doesn't fit reads as "none"."""
    if raw is None:
        return {}
    if not isinstance(raw, dict):
        return {}
    out: dict[str, str] = {}
    try:
        for k in BOT_TEXT_KEYS:
            v = _bot_text(raw.get(k))
            if v:
                out[k] = v
    except ValueError:
        return {}
    return out


def parse_showcase(raw: Any) -> dict[str, Any] | None:
    """The stored showcase settings, or None when they don't fit the schema."""
    if raw is None:
        raw = {"enabled": False}
    if not isinstance(raw, dict) or not isinstance(raw.get("enabled"), bool):
        return None
    try:
        out: dict[str, Any] = {
            "enabled": raw["enabled"],
            "link": _link(raw.get("link")),
            "assetIds": _asset_ids(raw.get("assetIds")),
        }
        text = _bot_text(raw.get("text"))
    except (ValueError, TypeError):
        return None
    if text:
        out["text"] = text
    return out


def disabled_showcase() -> dict[str, Any]:
    return {"enabled": False, "link": None, "assetIds": []}


